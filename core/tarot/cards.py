def build_all_cards():
    """
    构建完整的 78 张牌数据列表。
    每张牌 dict 包含：
      id, name, name_cn, suit, element, keywords_u, keywords_r,
      meaning_u, meaning_r, symbol, is_major
    """
    cards = []
    # 大牌
    for i, (key, data) in enumerate(MAJOR_DATA.items()):
        cards.append({
            "id": f"major_{i}",
            "name": data["en"],
            "name_cn": data["cn"],
            "suit": "major",
            "element": "spirit",
            "keywords_u": data["kw_u"],
            "keywords_r": data["kw_r"],
            "meaning_u": data["m_u"],
            "meaning_r": data["m_r"],
            "symbol": _major_symbol(i),
            "is_major": True,
            "ordinal": i,
        })
    # 小牌
    for suit, cards_data in _MINOR.items():
        element = {"wands": "fire", "cups": "water", "swords": "air", "pentacles": "earth"}[suit]
        for card_id, data in cards_data.items():
            symbol = SYMBOLS[suit][0]
            cards.append({
                "id": f"{suit}_{card_id}",
                "name": data["en"],
                "name_cn": data["cn"],
                "suit": suit,
                "element": element,
                "keywords_u": data["kw_u"],
                "keywords_r": data["kw_r"],
                "meaning_u": data["m_u"],
                "meaning_r": data["m_r"],
                "symbol": symbol,
                "is_major": False,
                "card_id": card_id,
            })
    return cards


def _major_symbol(idx: int) -> str:
    """大牌用罗马数字 + 序号作为显示符号"""
    roman = ["0", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX",
             "X", "XI", "XII", "XIII", "XIV", "XV", "XVI", "XVII", "XVIII", "XIX", "XX", "XXI"]
    return roman[idx]


def find_card(card_id: str):
    """根据 id 查找牌数据"""
    all_cards = build_all_cards()
    for c in all_cards:
        if c["id"] == card_id:
            return c
    return None


def all_cards_summary() -> list:
    """返回所有牌的摘要（name_cn + symbol），供 prompt 使用"""
    return [(c["symbol"], c["name_cn"], c["keywords_u"]) for c in build_all_cards()]
